#!/usr/bin/env python3
"""Convert a .cin table (e.g. PIME's mscj3.cin) to a Rime dict named cangjie3.base.

usage: cin2rime.py INPUT.cin OUTPUT.dict.yaml [--essay essay.txt]

* only %chardef entries are used
* only single-character entries are kept (multi-character entries are counted and skipped)
* codes are lower-cased
* candidates sharing a code keep their .cin order through descending weights:
  weight = 100000 - rank, rank counted per code starting at 0
  WITH --essay: weight = the character's frequency in essay.txt (min 1), clamped so that it
  stays below the previous candidate of the same code (still .cin order, but keeps word
  frequency information; without it all characters weigh ~100000 and sentence building
  prefers rare characters, e.g. nnm over nn+m. Measured in docs/test-log-cangjie3.md)
* identical (text, code) pairs are dropped (first one wins)
* output: UTF-8, no BOM, LF line endings

The .cin table itself has no known license: it is downloaded at install time and
must never be committed to this repository.
"""
import re
import sys

HEADER = (
    "# encoding: utf-8\n"
    "# Generated by tools/cin2rime.py from a .cin table. Do not commit this file.\n"
    "\n"
    "---\n"
    "name: cangjie3.base\n"
    'version: "1.0"\n'
    "sort: by_weight\n"
    "columns:\n"
    "  - text\n"
    "  - code\n"
    "  - weight\n"
    "...\n"
    "\n"
)


def load_essay(path):
    """single-character frequencies from essay.txt (text<TAB>weight); later lines win"""
    freq = {}
    with open(path, encoding="utf-8-sig") as f:
        for l in f.read().split("\n"):
            p = l.strip("\r").split("\t")
            if len(p) == 2 and len(p[0]) == 1 and p[1].isdigit():
                freq[p[0]] = int(p[1])
    return freq


def convert(src_lines, essay=None):
    prevw = {}
    in_chardef = False
    seen = set()
    rank = {}
    out = []
    n_entries = n_multi = n_dup = n_bad = 0
    for raw in src_lines:
        line = raw.strip(" \t\r")
        if not line:
            continue
        if line.startswith("%"):
            low = re.split(r"[ \t]+", line.lower())
            if low[0] == "%chardef" and len(low) > 1:
                in_chardef = low[1] == "begin"
            continue
        if not in_chardef:
            continue
        parts = re.split(r"[ \t]+", line)
        if len(parts) < 2:
            n_bad += 1
            continue
        code, text = parts[0].lower(), parts[1]
        n_entries += 1
        if len(text) != 1:  # Python str length = code points
            n_multi += 1
            continue
        if (text, code) in seen:
            n_dup += 1
            continue
        seen.add((text, code))
        r = rank.get(code, 0)
        rank[code] = r + 1
        if essay is None:
            w = 100000 - r
        else:
            w = max(essay.get(text, 0), 1)
            if code in prevw:
                w = min(w, prevw[code] - 1)
            w = max(w, 1)
            prevw[code] = w
        out.append("%s\t%s\t%d\n" % (text, code, w))
    stats = {"chardef_entries": n_entries, "multi_char_skipped": n_multi,
             "duplicates_skipped": n_dup, "malformed_skipped": n_bad,
             "written": len(out), "distinct_chars": len({t for t, _ in seen})}
    return out, stats


def main():
    args = sys.argv[1:]
    essay = None
    if len(args) == 4 and args[2] == "--essay":
        essay = load_essay(args[3])
        args = args[:2]
    if len(args) != 2:
        sys.exit(__doc__)
    sys.argv = [sys.argv[0]] + args
    with open(sys.argv[1], encoding="utf-8-sig", newline=None) as f:
        lines = f.read().split("\n")
    out, stats = convert(lines, essay)
    with open(sys.argv[2], "w", encoding="utf-8", newline="\n") as f:
        f.write(HEADER)
        f.writelines(out)
    for k, v in stats.items():
        print("%s: %d" % (k, v))


if __name__ == "__main__":
    main()
